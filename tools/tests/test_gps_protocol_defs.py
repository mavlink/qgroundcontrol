def test_validation_reports_disagreement(
    mutate: Callable[[dict[str, Any]], None], problem: str
) -> None:
    data = _manifest_data()
    mutate(data)
    with pytest.raises(DefinitionError) as error:
        _resolve(data)
    assert problem in error.value.problems


def test_validation_reports_every_problem() -> None:
    data = _manifest_data()
    _set(("ubx", "messages", "NAV-PVT"), [0x01, 0x08])(data)
    _set((*PVT, "id"), 4008)(data)
    with pytest.raises(DefinitionError) as error:
        _resolve(data)
    assert len(error.value.problems) == 2


def test_upstream_type_must_fit_its_key_id() -> None:
    ubx = _ubx()
    keys = dict(ubx.config_keys, CFG_RATE_MEAS=(0x30210001, "U004"))
    with pytest.raises(DefinitionError) as error:
        _resolve(_manifest_data(), UBXDatabase(ubx.version, ubx.classes, ubx.messages, keys))
    assert error.value.problems == [
        "UBX key CFG_RATE_MEAS: pyubx2 9.9 type U004 does not fit key id 0x30210001"
    ]


def test_irregular_msgout_port_offsets() -> None:
    ubx = _ubx()
    keys = dict(
        ubx.config_keys,
        CFG_MSGOUT_UBX_NAV_SAT_I2C=(0x20910015, "U001"),
        CFG_MSGOUT_UBX_NAV_SAT_UART1=(0x20910017, "U001"),
        CFG_MSGOUT_UBX_NAV_SAT_USB=(0x20910018, "U001"),
    )
    data = _manifest_data()
    data["ubx"]["msgout"]["CFG_MSGOUT_UBX_NAV_SAT"] = 0x20910015
    with pytest.raises(DefinitionError) as error:
        _resolve(data, UBXDatabase(ubx.version, ubx.classes, ubx.messages, keys))
    assert error.value.problems == [
        "UBX MSGOUT port UART1: pyubx2 9.9 key offsets from I2C differ: [1, 2]"
    ]


