def _resolve(data: dict[str, Any], ubx: UBXDatabase | None = None, sbf: SBFDatabase | None = None):
    return resolve(parse_manifest(data, "test"), ubx or _ubx(), sbf or _sbf())


def _reversed_tables(data: dict[str, Any]) -> dict[str, Any]:
    data = copy.deepcopy(data)
    for table in ("messages", "keys", "msgout"):
        data["ubx"][table] = dict(reversed(data["ubx"][table].items()))
    return data


