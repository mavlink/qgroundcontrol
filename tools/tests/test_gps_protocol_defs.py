def test_render_is_deterministic_and_independent_of_manifest_order() -> None:
    first = render(_resolve(_manifest_data()))
    assert first == render(_resolve(_manifest_data()))
    assert first == render(_resolve(_reversed_tables(_manifest_data())))
    assert set(first) == set(OUTPUTS.values())
    for text in first.values():
        assert text.splitlines()[0] == (
            "// Generated by tools/generators/gps_protocol_defs from pyubx2 9.9 / pysbf2 8.8 "
            "(BSD-3-Clause). Do not edit."
        )
        assert text.endswith("\n")
        assert not text.endswith("\n\n")


def test_resolved_definitions() -> None:
    definitions = _resolve(_manifest_data())
    assert [(m.constant, m.class_constant, m.id) for m in definitions.messages] == [
        ("NAV_PVT", "NAV", 0x07),
        ("CFG_VALSET", "CFG", 0x8A),
    ]
    assert [(k.constant, k.type, k.upstream_type) for k in definitions.keys] == [
        ("NAVSPG_DAHEADING_OFFSET", "int32_t", "U4"),
        ("RATE_MEAS", "uint16_t", "U2"),
        ("TMODE_LAT_HP", "int8_t", "I1"),
    ]
    assert [(p.name, p.offset) for p in definitions.ports] == [("UART1", 1), ("USB", 3)]
    assert definitions.msgout[0].port_ids == (("UART1", 0x20910007), ("USB", 0x20910009))
    block = definitions.blocks[0]
    assert (block.constant, block.size) == ("PVT_GEODETIC", 24)
    assert [(b.accessor, b.type, b.mask, b.shift) for b in block.fields[1].bits] == [
        ("modeType", "uint8_t", 0x0F, 0),
        ("mode2D", "bool", 0x80, 7),
    ]
    assert definitions.notes == (
        "UBX key CFG_NAVSPG_DAHEADING_OFFSET: QGC keeps int32_t; pyubx2 9.9 declares U004",
    )


def _set(path: tuple[str, ...], value: object) -> Callable[[dict[str, Any]], None]:
    def mutate(data: dict[str, Any]) -> None:
        node = data
        for key in path[:-1]:
            node = node[key]
        node[path[-1]] = value

    return mutate


def _delete(path: tuple[str, ...]) -> Callable[[dict[str, Any]], None]:
    def mutate(data: dict[str, Any]) -> None:
        node = data
        for key in path[:-1]:
            node = node[key]
        del node[path[-1]]

    return mutate


