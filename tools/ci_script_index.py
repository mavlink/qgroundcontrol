"""Generate the CI script index in tools/ci/README.md from the scripts' module docstrings.

Usage:
    python tools/ci_script_index.py           # Rewrite the index between its markers
    python tools/ci_script_index.py --check   # Exit 1 when the committed index is out of date

A package's scope is the first paragraph of its `__init__.py` docstring and a script's purpose
the first paragraph of its module docstring. "Used by" names the workflows, local actions, hook
and recipe files that name the script's path, and the CI scripts that import it.
"""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

import _bootstrap as _bootstrap
from common.logging import log_error, log_ok
from common.markdown import md_table
from common.paths import REPO_ROOT

README = Path("tools/ci/README.md")
START = "<!-- ci-script-index:start -->"
END = "<!-- ci-script-index:end -->"
NOTICE = "<!-- Generated by tools/ci_script_index.py from the module docstrings; do not edit. -->"
NO_DOCSTRING = "*(no module docstring)*"
# Files other than workflows and actions that run CI scripts by path.
OTHER_CALLERS = (".pre-commit-config.yaml", "justfile")

_RST_LITERAL = re.compile(r"``([^`]+)``")


def summary(path: Path) -> str:
    """First paragraph of *path*'s module docstring as one line of Markdown, or ''."""
    docstring = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8")))
    if not docstring:
        return ""
    paragraph = " ".join(docstring.split("\n\n", 1)[0].split())
    return _RST_LITERAL.sub(r"`\1`", paragraph)


def _imported_ci_modules(path: Path) -> set[str]:
    """Dotted names under `ci` that *path* imports; `from ci.x import y` may name module y."""
    modules: set[str] = set()
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Import):
            modules.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            modules.add(node.module)
            modules.update(f"{node.module}.{alias.name}" for alias in node.names)
    return {module for module in modules if module.startswith("ci.")}


def _callers(root: Path) -> dict[str, str]:
    """Display name and text of every file that can run a CI script by its path."""
    paths = {path.name: path for path in sorted((root / ".github/workflows").glob("*.yml"))}
    paths |= {
        f"actions/{path.parent.name}": path
        for path in sorted((root / ".github/actions").glob("*/action.yml"))
    }
    paths |= {name: root / name for name in OTHER_CALLERS}
    return {name: path.read_text(encoding="utf-8") for name, path in paths.items()}


def render_index(root: Path) -> str:
    """Return the index: one section per tools/ci package, one table row per script."""
    ci_dir = root / "tools/ci"
    scripts = sorted(path for path in ci_dir.rglob("*.py") if path.name != "__init__.py")
    callers = _callers(root)
    imports = {script: _imported_ci_modules(script) for script in scripts}

    sections = [START, NOTICE]
    for package in sorted({script.parent for script in scripts}):
        rows = []
        for script in (path for path in scripts if path.parent == package):
            name = script.relative_to(ci_dir).as_posix()
            named = re.compile(re.escape(f"tools/ci/{name}") + r"(?!\w)")
            module = "ci." + name.removesuffix(".py").replace("/", ".")
            used_by = [caller for caller, text in callers.items() if named.search(text)]
            used_by += [
                other.relative_to(ci_dir).as_posix()
                for other in scripts
                if module in imports[other]
            ]
            rows.append(
                (
                    f"`{name}`",
                    summary(script) or NO_DOCSTRING,
                    ", ".join(f"`{user}`" for user in used_by) or "—",
                )
            )
        init = package / "__init__.py"
        sections += [
            f"### `{package.relative_to(ci_dir).as_posix()}/`",
            (summary(init) if init.is_file() else "") or NO_DOCSTRING,
            md_table(("Script", "Purpose", "Used by"), rows, markdown=True),
        ]
    sections.append(END)
    return "\n\n".join(sections)


def replace_index(readme: str, index: str) -> str:
    """Return *readme* with the text between the index markers replaced by *index*."""
    start, end = readme.find(START), readme.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{README} needs the {START} and {END} markers, in that order")
    return readme[:start] + index + readme[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the CI script index in tools/ci/README.md from module docstrings."
    )
    parser.add_argument(
        "--check", action="store_true", help="verify the committed index instead of rewriting it"
    )
    args = parser.parse_args(argv)

    readme_path = REPO_ROOT / README
    current = readme_path.read_text(encoding="utf-8")
    try:
        updated = replace_index(current, render_index(REPO_ROOT))
    except ValueError as error:
        log_error(str(error))
        return 1
    if updated == current:
        log_ok(f"{README} script index is up to date")
        return 0
    if args.check:
        log_error(
            f"{README} script index is out of date; run "
            "`uv run --frozen --project tools python tools/ci_script_index.py`"
        )
        return 1
    readme_path.write_text(updated, encoding="utf-8", newline="\n")
    log_ok(f"Updated the script index in {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
