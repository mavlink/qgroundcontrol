"""Render the checked-in UBX and SBF definition headers from manifest.toml and the pinned upstream databases."""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path

from common.io import write_text_if_changed

from generators._jinja import make_env

from .definitions import DefinitionError, Definitions, resolve
from .manifest import load_manifest
from .upstream import UpstreamError, load_sbf, load_ubx

REPO_ROOT = Path(__file__).resolve().parents[3]
TEMPLATES_DIR = Path(__file__).with_name("templates")
OUTPUTS = {
    "UBXMessageIds.h.j2": Path("src/GPS/Protocols/UBX/Generated/UBXMessageIds.h"),
    "UBXConfigKeys.h.j2": Path("src/GPS/Protocols/UBX/Generated/UBXConfigKeys.h"),
    "SBFBlocks.h.j2": Path("src/GPS/Protocols/SBF/Generated/SBFBlocks.h"),
}


def attribution(definitions: Definitions) -> str:
    return (
        f"// Generated by tools/generators/gps_protocol_defs from pyubx2 {definitions.ubx_version} / "
        f"pysbf2 {definitions.sbf_version} (BSD-3-Clause). Do not edit."
    )


def render(definitions: Definitions) -> dict[Path, str]:
    """Unformatted header text by repository-relative path."""
    env = make_env(TEMPLATES_DIR)
    env.keep_trailing_newline = True
    env.filters["hex"] = lambda value, digits: f"0x{value:0{digits}x}"
    return {
        path: env.get_template(template).render(
            defs=definitions, attribution=attribution(definitions)
        )
        for template, path in OUTPUTS.items()
    }


def clang_format_command() -> list[str]:
    """The pinned clang-format of the running environment, so output does not depend on the host."""
    executable = shutil.which("clang-format", path=sysconfig.get_path("scripts")) or shutil.which(
        "clang-format"
    )
    if executable is None:
        raise UpstreamError("clang-format is not installed; run with the gps-defs dependency group")
    return [executable, f"--style=file:{REPO_ROOT / '.clang-format'}"]


def clang_format(text: str, path: Path) -> str:
    result = subprocess.run(
        [*clang_format_command(), f"--assume-filename={path.name}"],
        input=text,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise UpstreamError(f"clang-format failed for {path}: {result.stderr.strip()}")
    return result.stdout


def generate() -> dict[Path, str]:
    """Formatted header text by repository-relative path; raises DefinitionError on any disagreement."""
    definitions = resolve(load_manifest(), load_ubx(), load_sbf())
    for note in definitions.notes:
        print(f"note: {note}")
    return {path: clang_format(text, path) for path, text in render(definitions).items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when a checked-in header differs, without writing",
    )
    parser.add_argument(
        "--output-root", type=Path, default=REPO_ROOT, help="Root the header paths are relative to"
    )
    args = parser.parse_args(argv)

    try:
        headers = generate()
    except DefinitionError as error:
        for problem in error.problems:
            print(f"error: {problem}", file=sys.stderr)
        print(
            "error: manifest.toml disagrees with upstream; nothing was generated", file=sys.stderr
        )
        return 1
    except UpstreamError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    stale = []
    for relative, text in headers.items():
        path = args.output_root / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        print(f"{'Generated' if write_text_if_changed(path, text) else 'Unchanged'}: {relative}")
    for relative in stale:
        print(f"error: {relative} is out of date; rerun the generator", file=sys.stderr)
    return 1 if stale else 0
